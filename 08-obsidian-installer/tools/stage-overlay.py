#!/usr/bin/env python3
"""Stage the Obsidian OS 1.0 overlay from the verified console pull.

Input:
  build/console-pull/            tree pulled from the console (SHA-256 recorded)
  <repo>/01-projeto/jogos-originais/fbneo_libretro.so
  <repo>/08-obsidian-installer/assets/bootstrap/...   (not used here)

Output:
  build/image-overlay/p1/...     files destined to the ext4 rootfs
  build/image-overlay/p2/...     files destined to the FAT32 home
  build/image-overlay/overlay.json   component manifest (path, sha256, size, origin)
  build/image-overlay.tar        archive consumed by tools/apply-image.sh

Curation rules remove everything that is personal, experimental or a local
backup: launcher backups, book indexes, reader positions, favorites, saves,
save states, screenshots, retroarch playlists, DraStic test ROMs and the
laboratory boot diagnostics.
"""
from __future__ import annotations

import hashlib
import json
import os
import shutil
import sys
import tarfile
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent          # 08-obsidian-installer
REPO = ROOT.parent                                      # R36S-sistema-novo
PULL = ROOT / "build" / "console-pull"
STAGE = ROOT / "build" / "image-overlay"
TAR_OUT = ROOT / "build" / "image-overlay.tar"

PRODUCT = "Obsidian OS"
VERSION = "1.0"
BUILD_ID = time.strftime("%Y%m%d", time.gmtime())
BASE_IMAGE = "Obsisidian-prova-USB-base-goodluck-20261029.img"
BASE_SHA256 = "a113b3c53a0d2c2c319f4ada65a694ccb6b16dbed053458a32669ba47b7ae7c5"
EXPECTED_LAUNCHER_SHA = "de6fa0a3ac98c529c429554755cab021a5a7c85197acf8b12d4bef420165c018"
EXPECTED_APPCTL_SHA = "e4f612e9b587c778fd8aae4c90c1c7b0943f3fff6b61e0b889ebd2c67c4cd4cc"

EXECUTABLE_NAMES = {
    "appctl", "brightstep.sh", "rcS", "S99appd", "S00gameman-quiet", "S12gameman-splash",
    "S29obsidian-data", "gameman-launcher", "launcher.sh", "fn-home.sh", "power-button.sh",
    "launcher.puppy-backup.sh", "drastic", "drastic.sh", "ffplay-obsidian", "reproduzir.sh",
    "fbneo_libretro.so",
}

# Paths (relative to home/player) that must not ship: personal data and lab backups.
HOME_EXCLUDE_PREFIXES = (
    ".config/gameman/",
    ".config/retroarch/saves/",
    ".config/retroarch/states/",
    ".config/retroarch/screenshots/",
    ".config/retroarch/logs/",
    ".config/retroarch/playlists/",
)
HOME_EXCLUDE_SUBSTR = (
    ".before-", ".before_", "gameman-state", "input_capture_crash.ir", "diagnostico-hardware",
)
INITD_EXCLUDE = {"S98gameman-diagnostico"}
# Substituídos por versões instrumentadas/defensivas geradas abaixo.
GENERATED_INITD = {"rcS", "S00gameman-quiet", "S12gameman-splash", "S29obsidian-data"}


def sha256_of(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for block in iter(lambda: fh.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def os_release() -> str:
    return (
        f'NAME="{PRODUCT}"\n'
        f'PRETTY_NAME="{PRODUCT} {VERSION}"\n'
        f'VERSION="{VERSION}"\n'
        'VERSION_ID="1.0"\n'
        f'BUILD_ID="{BUILD_ID}"\n'
        # Kept for compatibility with the vendor base scripts and services.
        'ID=goodluckos\n'
        'ID_LIKE=goodluckos\n'
        'HOME_URL="https://obsidian.local/"\n'
        'ARCHITECTURE="armv7l"\n'
    )


def obsidian_release(manifest: dict, component_count: int) -> str:
    return (
        "# Obsidian OS release marker — generated by tools/stage-overlay.py\n"
        f"PRODUCT={PRODUCT}\n"
        f"VERSION={VERSION}\n"
        f"BUILD_ID={BUILD_ID}\n"
        f"BASE_IMAGE={BASE_IMAGE}\n"
        f"BASE_SHA256={BASE_SHA256}\n"
        f"LAUNCHER_SHA256={manifest['launcher_sha256']}\n"
        f"APPCTL_SHA256={EXPECTED_APPCTL_SHA}\n"
        f"COMPONENTS={component_count}\n"
        "LAYOUT=rootfs(ext4,384MiB)+home(fat32,512MiB)+data(OBSIDIAN,fat32,rest of card)\n"
    )


def readme_home() -> str:
    return (
        "Obsidian OS 1.0 — cartão do sistema\r\n"
        "===================================\r\n\r\n"
        "Este cartão (TF1) é o sistema. A área de conteúdo fica na partição\r\n"
        "OBSIDIAN, montada no console em /media/obsidian, e no cartão de jogos (TF2).\r\n\r\n"
        "Onde colocar conteúdo:\r\n"
        "  /media/obsidian/leitura   livros EPUB/CBZ\r\n"
        "  /media/obsidian/videos    séries e episódios (MP4/M4V/MOV)\r\n"
        "  /media/external/roms      jogos por console (TF2)\r\n"
        "  /media/external/leitura   livros no cartão de jogos (opcional)\r\n"
        "  /media/external/videos    vídeos no cartão de jogos (opcional)\r\n\r\n"
        "O instalador do Windows grava esta imagem, prepara a partição OBSIDIAN\r\n"
        "e restaura o backup de conteúdo.\r\n"
    )


def add_file(stage_root: Path, partition: str, rel_path: str, source: Path, origin: str,
             components: list[dict]) -> None:
    target = stage_root / partition / rel_path
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(source, target)
    components.append({
        "partition": partition,
        "path": rel_path.replace("\\", "/"),
        "sha256": sha256_of(target),
        "size": target.stat().st_size,
        "origin": origin,
    })


def add_text(stage_root: Path, partition: str, rel_path: str, text: str, origin: str,
             components: list[dict]) -> None:
    target = stage_root / partition / rel_path
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(text.encode("utf-8"))
    components.append({
        "partition": partition,
        "path": rel_path.replace("\\", "/"),
        "sha256": sha256_of(target),
        "size": target.stat().st_size,
        "origin": origin,
    })



EXEC_DIRS = ("etc/init.d/", "usr/local/bin/", "usr/bin/", "usr/sbin/", "sbin/", "bin/")


def mode_for(part: str, path: Path) -> int:
    """Modo no tar. A árvore de staging vive em NTFS e perde o bit +x; a regra
    é explícita: diretórios de serviço/binários e qualquer arquivo com #! são
    executáveis. Sem isso, o init da base recebe Permission denied e o sistema
    não inicializa (defeito encontrado no diário de boot da r1/r2)."""
    if path.is_dir():
        return 0o755
    rel = path.relative_to(STAGE / part).as_posix()
    if rel.startswith(EXEC_DIRS):
        return 0o755
    if path.name in EXECUTABLE_NAMES:
        return 0o755
    try:
        if path.stat().st_size < 1_000_000 and path.read_bytes()[:2] == b"#!":
            return 0o755
    except OSError:
        pass
    return 0o644


def without_dir(path: Path, exclude: set[str]) -> bool:
    return not (set(part for part in path.parts) & exclude)


def main() -> int:
    if not PULL.is_dir():
        print(f"console pull missing: {PULL}", file=sys.stderr)
        return 2
    pull_hash_file = PULL / "PULL-SHA256.txt"
    pull_hash = pull_hash_file.read_text(encoding="ascii").split()[0] if pull_hash_file.exists() else "unknown"

    if STAGE.exists():
        shutil.rmtree(STAGE)
    (STAGE / "p1").mkdir(parents=True)
    (STAGE / "p2").mkdir(parents=True)
    components: list[dict] = []

    # ---- rootfs (p1) ----------------------------------------------------
    for src in sorted((PULL / "etc" / "init.d").iterdir()):
        if not src.is_file():
            continue
        if src.name in INITD_EXCLUDE or ".before-" in src.name or src.name in GENERATED_INITD:
            continue
        add_file(STAGE, "p1", f"etc/init.d/{src.name}", src, "console:/etc/init.d", components)

    for src in sorted((PULL / "etc" / "triggerhappy" / "triggers.d").iterdir()):
        if src.is_file():
            add_file(STAGE, "p1", f"etc/triggerhappy/triggers.d/{src.name}", src,
                     "console:/etc/triggerhappy/triggers.d", components)

    umtprd = PULL / "etc" / "umtprd" / "umtprd.conf"
    add_file(STAGE, "p1", "etc/umtprd/umtprd.conf", umtprd, "console:/etc/umtprd", components)
    add_file(STAGE, "p1", "etc/fstab", PULL / "etc" / "fstab", "console:/etc/fstab", components)

    for name in ("appctl", "brightstep.sh"):
        src = PULL / "usr" / "local" / "bin" / name
        add_file(STAGE, "p1", f"usr/local/bin/{name}", src, "console:/usr/local/bin", components)

    # ---- identity -------------------------------------------------------
    # Added after the home tree so the release marker can record the launcher hash.

    # ---- home (p2) ------------------------------------------------------
    home = PULL / "home" / "player"
    skipped: list[str] = []
    for src in sorted(home.rglob("*")):
        rel = src.relative_to(home).as_posix()
        if src.is_dir():
            if any(rel.startswith(p.rstrip("/")) for p in HOME_EXCLUDE_PREFIXES):
                skipped.append(rel + "/")
                continue
            (STAGE / "p2" / rel).mkdir(parents=True, exist_ok=True)
            continue
        if any(rel.startswith(p) for p in HOME_EXCLUDE_PREFIXES) or any(s in rel for s in HOME_EXCLUDE_SUBSTR):
            skipped.append(rel)
            continue
        add_file(STAGE, "p2", rel, src, "console:/home/player", components)

    # ---- extra components kept in the project (not pulled over serial) ---
    fbneo = REPO / "01-projeto" / "jogos-originais" / "fbneo_libretro.so"
    add_file(STAGE, "p2", "fbneo_libretro.so", fbneo, "project:01-projeto/jogos-originais", components)

    # Empty folders the launcher scans, so the first boot has a clean structure.
    for folder in ("leitura", "videos", "roms/cps2", "roms/cps3", "roms/psp", "roms/nds",
                   ".config/retroarch/saves", ".config/retroarch/states"):
        (STAGE / "p2" / folder).mkdir(parents=True, exist_ok=True)
    add_text(STAGE, "p2", "LEIA-ME-OBSIDIAN.txt", readme_home(), "generated", components)

    launcher = STAGE / "p2" / "gameman-launcher"
    launcher_sha = sha256_of(launcher)
    if launcher_sha != EXPECTED_LAUNCHER_SHA:
        print(f"launcher hash mismatch: {launcher_sha}", file=sys.stderr)
        return 3
    appctl_sha = sha256_of(STAGE / "p1" / "usr" / "local" / "bin" / "appctl")
    if appctl_sha != EXPECTED_APPCTL_SHA:
        print(f"appctl hash mismatch: {appctl_sha}", file=sys.stderr)
        return 3

    # ---- boot instrumentation and defensive init ---------------------
    boot_rcs = """#!/bin/sh
# Obsidian OS: executa os serviços em ordem e registra o diário de boot na
# partição HOME (FAT32), que é legível no Windows mesmo quando o sistema falha.
if mkdir -p /home/player 2>/dev/null && : > /home/player/boot-rc.log 2>/dev/null; then
    LOG=/home/player/boot-rc.log
else
    LOG=/dev/shm/boot-rc.log
fi
exec >>"$LOG" 2>&1
echo "=== rcS $(date) ==="
for i in /etc/init.d/S??*; do
    case "$i" in
        *.sh) . "$i" start ;;
        *) echo "--- $(date +%s) inicio $i"; "$i" start; echo "--- $(date +%s) fim $i rc=$?" ;;
    esac
done
echo "=== rcS concluido $(date) ==="
"""
    add_text(STAGE, "p1", "etc/init.d/rcS", boot_rcs, "generated", components)

    splash = """#!/bin/sh
# Obsidian OS: splash antecipada. Nada aqui pode bloquear o init.
case "$1" in
    start)
        rm -f /dev/shm/gameman-splash-stop /dev/shm/gameman-splash-running /dev/shm/gameman-splash.pid /dev/shm/gameman-splash-ready /dev/shm/gameman-splash.log
        echo "[S12] inicio $(date +%s)" >>/dev/shm/rc.log 2>&1
        chown player:player /dev/tty1 2>/dev/null
        chmod 620 /dev/tty1 2>/dev/null
        /etc/init.d/S90backlight start >/dev/null 2>&1 &
        if [ -x /home/player/gameman-launcher ]; then
            : > /dev/shm/gameman-splash-armed
            setsid su -l -s /bin/sh player -c "/home/player/gameman-launcher --splash" >/dev/shm/gameman-splash.log 2>&1 &
        fi
        echo "[S12] fim $(date +%s)" >>/dev/shm/rc.log 2>&1
        ;;
    stop)
        : > /dev/shm/gameman-splash-stop
        ;;
esac
exit 0
"""
    add_text(STAGE, "p1", "etc/init.d/S12gameman-splash", splash, "generated", components)

    data_mount = """#!/bin/sh
# Monta a partição de dados OBSIDIAN se ela existir e for identificada.
# Nunca particiona, nunca formata e nunca interrompe o boot.
case "$1" in
 start)
  part=/dev/mmcblk0p3
  mountpoint -q /media/obsidian && exit 0
  [ -b "$part" ] || exit 0
  if command -v blkid >/dev/null 2>&1; then
      info=$(blkid "$part" 2>/dev/null) || info=""
      case "$info" in
          *'LABEL="OBSIDIAN"'*'TYPE="vfat"'*) ;;
          *) [ -n "$info" ] && echo "Obsidian data: identidade nao confere" >&2; exit 0 ;;
      esac
  fi
  mkdir -p /media/obsidian
  mount -t vfat -o rw,noatime,uid=1000,gid=1000,umask=022 "$part" /media/obsidian || exit 0
  ;;
 stop) : ;;
esac
exit 0
"""
    add_text(STAGE, "p1", "etc/init.d/S29obsidian-data", data_mount, "generated", components)

    quiet = """#!/bin/sh
# Obsidian OS: silencia o console antes da splash.
case "$1" in
    start)
        echo "[S00] inicio $(date +%s)" >>/dev/shm/rc.log 2>&1
        dmesg -n 1 2>/dev/null
        chown player:player /dev/tty1 2>/dev/null
        chmod 620 /dev/tty1 2>/dev/null
        printf '\\033[2J\\033[H\\033[?25l' >/dev/tty1 2>/dev/null
        ;;
esac
exit 0
"""
    add_text(STAGE, "p1", "etc/init.d/S00gameman-quiet", quiet, "generated", components)

    # ---- identity (rootfs) ---------------------------------------------
    add_text(STAGE, "p1", "etc/os-release", os_release(), "generated", components)
    add_text(STAGE, "p1", "etc/issue", "Obsidian OS 1.0 \\n \\l\n\n", "generated", components)
    add_text(STAGE, "p1", "etc/hostname", "obsidian\n", "generated", components)
    add_text(STAGE, "p1", "etc/hosts", "127.0.0.1\tlocalhost\n127.0.1.1\tobsidian\n", "generated", components)
    add_text(STAGE, "p1", "etc/obsidian-release",
             obsidian_release({"launcher_sha256": launcher_sha}, len(components) + 1),
             "generated", components)

    manifest = {
        "product": PRODUCT,
        "version": VERSION,
        "build_id": BUILD_ID,
        "generated_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "base_image": BASE_IMAGE,
        "base_sha256": BASE_SHA256,
        "console_pull_sha256": pull_hash,
        "launcher_sha256": launcher_sha,
        "appctl_sha256": appctl_sha,
        "skipped_paths": skipped,
        "components": components,
        "summary": {
            "files": len(components),
            "bytes": sum(c["size"] for c in components),
            "by_partition": {
                part: {"files": sum(1 for c in components if c["partition"] == part),
                       "bytes": sum(c["size"] for c in components if c["partition"] == part)}
                for part in ("p1", "p2")
            },
        },
    }
    (STAGE / "overlay.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n",
                                        encoding="utf-8")
    shutil.copy2(STAGE / "overlay.json", ROOT / "build" / "overlay.json")

    # ---- final archive --------------------------------------------------
    with tarfile.open(TAR_OUT, "w", format=tarfile.PAX_FORMAT) as tar:
        for part in ("p1", "p2"):
            for path in sorted((STAGE / part).rglob("*")):
                arc = Path(part) / path.relative_to(STAGE / part)
                info = tar.gettarinfo(str(path), arcname=arc.as_posix())
                info.uid = info.gid = 0
                info.uname = info.gname = "root"
                info.mode = mode_for(part, path)
                if path.is_file():
                    with path.open("rb") as fh:
                        tar.addfile(info, fh)
                else:
                    tar.addfile(info)

    print(json.dumps(manifest["summary"], ensure_ascii=False, indent=2))
    print(f"launcher sha256: {launcher_sha}")
    print(f"skipped (personal/lab): {len(skipped)} paths")
    print(f"archive: {TAR_OUT} ({TAR_OUT.stat().st_size/2**20:.1f} MiB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
